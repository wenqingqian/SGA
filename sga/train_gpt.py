"""SGA GPT training entry (torchrun target).

Thin wrapper over megatron's stock pretrain_gpt: forward_step, loss_func,
dataset provider, model_provider and embedding-rank logic are imported
unchanged from the upstream module, and parse_and_validate_args receives the
same extra_args_provider / args_defaults as upstream pretrain_gpt.__main__, so
dense semantics stay byte-identical to the official core_r0.18.0 entry. The
only SGA-owned piece is the model registry lookup (SGA_MODEL env var, default
llama-1b) that feeds the provider chain.

Usage (generated by the SGA launcher):
    torchrun ... ./sga/train_gpt.py --num-layers 16 ...
"""

import os
import pickle
import time
from functools import partial

import torch

# Default the model selection before __main__ reads SGA_MODEL.
os.environ.setdefault("SGA_MODEL", "llama-1b")

# The upstream entry module (Megatron-LM root is on PYTHONPATH via env.sh).
# Importing it provides the stock implementations we reuse below.
import pretrain_gpt  # noqa: E402  (isort: skip - must follow the env setup)

from megatron.training import inprocess_restart, pretrain  # noqa: E402
from megatron.training.argument_utils import pretrain_cfg_container_from_args  # noqa: E402
from megatron.training.arguments import parse_and_validate_args  # noqa: E402

from sga.models import get_model, register_default_models  # noqa: E402

# Same conditional provider set as upstream pretrain_gpt.__main__.
try:
    from megatron.post_training.arguments import add_modelopt_args  # noqa: E402

    has_nvidia_modelopt = True
except ImportError:
    has_nvidia_modelopt = False


def _sga_resume_guard(args) -> None:
    """Refuse resuming a checkpoint whose saved sga_config differs from the
    current one unless --sga-allow-config-override is set. Fail-closed
    semantics: an absent/empty saved config counts as a mismatch too (a
    legacy DENSE checkpoint must not silently resume under an active SGA
    config), and any load/parse failure refuses the resume instead of
    proceeding — the override flag is the single sanctioned escape hatch.
    A MISSING tracker file passes: mirroring megatron's load_checkpoint,
    no saved state under --load means a cold start, not a resume.

    SGA-repo-side guard (no 6th fork site): rank 0 peeks the checkpoint's
    saved args BEFORE pretrain(). torch.distributed is not initialized at
    this point, so the rank comes from the RANK env var (torchrun exports
    it before process launch; bare single-process runs default to 0) — this
    also means only rank 0 pays the checkpoint-load cost instead of every
    rank. On refusal rank 0 exits non-zero and torchrun's elastic agent
    tears down the whole job, so no distributed handshake is needed here.

    Deserialization keeps torch.load's default weights_only=True; legacy
    checkpoints deserialize because importing megatron.core above (via
    pretrain_gpt / megatron.training) registered argparse.Namespace etc.
    through register_safe_globals() at import time.
    """
    import json
    import logging

    sga_config = getattr(args, "sga_config", "")
    if not sga_config or not getattr(args, "load", None):
        return
    if getattr(args, "sga_allow_config_override", False):
        return

    logger = logging.getLogger(__name__)
    try:
        rank = int(os.environ.get("RANK", "0"))
    except ValueError:
        rank = 0
    if rank != 0:
        return

    def _canonical(text):
        payload = json.loads(text)
        if not isinstance(payload, dict):
            raise ValueError("sga_config is not a JSON object")
        return json.dumps(payload, sort_keys=True, separators=(",", ":"))

    same = False
    detail = ""
    try:
        from megatron.training.checkpointing import (
            get_checkpoint_name,
            get_checkpoint_tracker_filename,
        )

        tracker = get_checkpoint_tracker_filename(args.load)
        if not os.path.exists(tracker):
            # Megatron's own convention: an absent tracker under --load means
            # nothing was saved there yet and the run cold-starts — there is
            # no saved config to compare against.
            return
        with open(tracker) as f:
            iterations = [int(line) for line in f.read().split() if line.isdigit()]
        if not iterations:
            # release-style tracker (content "release") or an empty file:
            # megatron loads the release weights at iteration 0 — there is no
            # prior SGA state to be continuous with, so nothing to verify.
            return
        # Rank-shard discovery WITHOUT get_checkpoint_name's defaults: those
        # consult parallel_state, which pretrain() has not initialized yet.
        # Every rank shard of an iteration embeds the same saved args, so
        # picking the lexicographically first one is sufficient (and covers
        # tp/pp/expert shard layouts). Absent shards = unsupported format =
        # fail-closed below.
        from pathlib import Path

        iter_dir = Path(get_checkpoint_name(args.load, max(iterations),
                                            return_base_dir=True))
        shards = sorted(iter_dir.glob("mp_rank_*/model_optim_rng.pt"))
        if not shards:
            raise OSError(f"no model_optim_rng.pt rank shard under {iter_dir}")
        state = torch.load(shards[0], map_location="cpu")
        saved = getattr(state.get("args", None), "sga_config", "")
        if isinstance(saved, str) and saved:
            same = _canonical(saved) == _canonical(sga_config)
            if not same:
                detail = "checkpoint sga_config differs from the current --sga-config"
        else:
            detail = "checkpoint carries no saved sga_config"
    except (OSError, AttributeError, KeyError, TypeError, ValueError,
            RuntimeError, pickle.UnpicklingError) as e:
        detail = f"could not verify the checkpoint's saved sga_config ({e})"
    if not same:
        logger.error(
            "%s; refusing the SGA resume (pass --sga-allow-config-override "
            "to override)", detail,
        )
        raise SystemExit(1)


if __name__ == "__main__":
    _PROGRAM_START_TIME = getattr(pretrain_gpt, "_PROGRAM_START_TIME", time.time())
    _MAIN_ENTRY_TIME = time.time()
    from megatron.training import set_startup_timestamps

    set_startup_timestamps(program_start=_PROGRAM_START_TIME, main_entry=_MAIN_ENTRY_TIME)

    register_default_models()
    entry = get_model(os.environ["SGA_MODEL"])

    # upstream stock pieces (loss_func / forward_step / dataset provider)
    setattr(pretrain_gpt.train_valid_test_datasets_provider, "is_distributed", True)
    pretrain, store = inprocess_restart.maybe_wrap_for_inprocess_restart(pretrain)

    args = parse_and_validate_args(
        extra_args_provider=add_modelopt_args if has_nvidia_modelopt else None,
        args_defaults={"tokenizer_type": "GPT2BPETokenizer"},
    )
    _sga_resume_guard(args)
    full_config = pretrain_cfg_container_from_args(args)
    pretrain(
        full_config,
        pretrain_gpt.train_valid_test_datasets_provider,
        partial(pretrain_gpt.model_provider, entry["builder"]),
        entry["model_type"],
        pretrain_gpt.forward_step,
        store=store,
        get_embedding_ranks=pretrain_gpt.get_embedding_ranks,
    )
