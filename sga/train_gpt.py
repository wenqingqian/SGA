"""SGA GPT training entry (torchrun target).

Thin wrapper over megatron's stock pretrain_gpt: forward_step, loss_func,
dataset provider, model_provider and embedding-rank logic are imported
unchanged from the upstream module, and parse_and_validate_args receives the
same extra_args_provider / args_defaults as upstream pretrain_gpt.__main__, so
dense semantics stay byte-identical to the official core_r0.18.0 entry. The
only SGA-owned piece is the model registry lookup (SGA_MODEL env var, default
llama-1b) that feeds the provider chain.

Usage (generated by the SGA launcher):
    torchrun ... ./sga/train_gpt.py --num-layers 16 ...
"""

import os
import time
from functools import partial

# Default the model selection before __main__ reads SGA_MODEL.
os.environ.setdefault("SGA_MODEL", "llama-1b")

# The upstream entry module (Megatron-LM root is on PYTHONPATH via env.sh).
# Importing it provides the stock implementations we reuse below.
import pretrain_gpt  # noqa: E402  (isort: skip - must follow the env setup)

from megatron.training import inprocess_restart, pretrain  # noqa: E402
from megatron.training.argument_utils import pretrain_cfg_container_from_args  # noqa: E402
from megatron.training.arguments import parse_and_validate_args  # noqa: E402

from sga.models import get_model, register_default_models  # noqa: E402

# Same conditional provider set as upstream pretrain_gpt.__main__.
try:
    from megatron.post_training.arguments import add_modelopt_args  # noqa: E402

    has_nvidia_modelopt = True
except ImportError:
    has_nvidia_modelopt = False


if __name__ == "__main__":
    _PROGRAM_START_TIME = getattr(pretrain_gpt, "_PROGRAM_START_TIME", time.time())
    _MAIN_ENTRY_TIME = time.time()
    from megatron.training import set_startup_timestamps

    set_startup_timestamps(program_start=_PROGRAM_START_TIME, main_entry=_MAIN_ENTRY_TIME)

    register_default_models()
    entry = get_model(os.environ["SGA_MODEL"])

    # upstream stock pieces (loss_func / forward_step / dataset provider)
    setattr(pretrain_gpt.train_valid_test_datasets_provider, "is_distributed", True)
    pretrain, store = inprocess_restart.maybe_wrap_for_inprocess_restart(pretrain)

    args = parse_and_validate_args(
        extra_args_provider=add_modelopt_args if has_nvidia_modelopt else None,
        args_defaults={"tokenizer_type": "GPT2BPETokenizer"},
    )
    full_config = pretrain_cfg_container_from_args(args)
    pretrain(
        full_config,
        pretrain_gpt.train_valid_test_datasets_provider,
        partial(pretrain_gpt.model_provider, entry["builder"]),
        entry["model_type"],
        pretrain_gpt.forward_step,
        store=store,
        get_embedding_ranks=pretrain_gpt.get_embedding_ranks,
    )
